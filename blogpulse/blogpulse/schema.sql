DROP VIEW     IF EXISTS v_user_overview, v_monthly_signups;
DROP TABLE    IF EXISTS account_audit_log, user_logins, subscriptions,
                        users, plans, countries, roles CASCADE;
DROP FUNCTION IF EXISTS fn_log_account_change(), fn_close_previous_subscription();

-- ---------------------------------------------------------------------
-- 1. Lookup tables (each non-key fact is stored exactly once -> 3NF)
-- ---------------------------------------------------------------------
CREATE TABLE roles (
    role_id      SMALLINT     PRIMARY KEY,
    role_name    VARCHAR(20)  NOT NULL UNIQUE
                 CHECK (role_name IN ('admin','editor','author','reader')),
    description  VARCHAR(200) NOT NULL,
    can_publish  BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE countries (
    country_code CHAR(2)      PRIMARY KEY,
    country_name VARCHAR(60)  NOT NULL UNIQUE,
    region       VARCHAR(30)  NOT NULL
);

CREATE TABLE plans (
    plan_id             SMALLINT     PRIMARY KEY,
    plan_name           VARCHAR(20)  NOT NULL UNIQUE,
    monthly_price       NUMERIC(8,2) NOT NULL CHECK (monthly_price >= 0),
    max_posts_per_month INT          NOT NULL CHECK (max_posts_per_month > 0)
);

-- ---------------------------------------------------------------------
-- 2. Users (FK -> roles, countries)
-- ---------------------------------------------------------------------
CREATE TABLE users (
    user_id       INT          PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    username      VARCHAR(30)  NOT NULL UNIQUE,
    full_name     VARCHAR(80)  NOT NULL,
    email         VARCHAR(120) NOT NULL UNIQUE
                  CHECK (email LIKE '_%@_%.__%'),
    password_hash CHAR(64)     NOT NULL,
    role_id       SMALLINT     NOT NULL REFERENCES roles(role_id),
    country_code  CHAR(2)      NOT NULL REFERENCES countries(country_code),
    signup_date   DATE         NOT NULL DEFAULT CURRENT_DATE,
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE
);
-- e-mail must be unique regardless of letter case
CREATE UNIQUE INDEX ux_users_email_lower ON users (LOWER(email));
CREATE INDEX ix_users_role    ON users (role_id);
CREATE INDEX ix_users_signup  ON users (signup_date);

-- ---------------------------------------------------------------------
-- 3. Subscriptions (a user can have many over time, only ONE active)
-- ---------------------------------------------------------------------
CREATE TABLE subscriptions (
    subscription_id INT         PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id         INT         NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    plan_id         SMALLINT    NOT NULL REFERENCES plans(plan_id),
    start_date      DATE        NOT NULL,
    end_date        DATE,
    status          VARCHAR(10) NOT NULL
                    CHECK (status IN ('active','expired','cancelled')),
    CHECK (end_date IS NULL OR end_date > start_date),
    CHECK (status <> 'active' OR end_date IS NULL)
);
CREATE UNIQUE INDEX ux_one_active_sub_per_user
    ON subscriptions (user_id) WHERE status = 'active';

-- ---------------------------------------------------------------------
-- 4. Login events (basis for "active users")
-- ---------------------------------------------------------------------
CREATE TABLE user_logins (
    login_id  BIGINT      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id   INT         NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    login_at  TIMESTAMP   NOT NULL,
    device    VARCHAR(10) NOT NULL CHECK (device IN ('web','android','ios'))
);
CREATE INDEX ix_logins_user ON user_logins (user_id, login_at);
CREATE INDEX ix_logins_time ON user_logins (login_at);

-- ---------------------------------------------------------------------
-- 5. Audit log (filled automatically by trigger trg_users_audit)
-- ---------------------------------------------------------------------
CREATE TABLE account_audit_log (
    log_id     BIGINT      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id    INT         REFERENCES users(user_id) ON DELETE SET NULL,
    action     VARCHAR(30) NOT NULL,
    old_value  VARCHAR(120),
    new_value  VARCHAR(120),
    changed_at TIMESTAMP   NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_audit_user ON account_audit_log (user_id, changed_at);

-- ---------------------------------------------------------------------
-- TRIGGER 1: log every account creation and every change to role,
--            e-mail or active flag ("trigger to log account changes")
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_log_account_change() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO account_audit_log (user_id, action, new_value)
        SELECT NEW.user_id, 'ACCOUNT_CREATED', r.role_name
        FROM roles r WHERE r.role_id = NEW.role_id;

    ELSIF TG_OP = 'UPDATE' THEN
        IF NEW.role_id IS DISTINCT FROM OLD.role_id THEN
            INSERT INTO account_audit_log (user_id, action, old_value, new_value)
            VALUES (NEW.user_id, 'ROLE_CHANGED',
                    (SELECT role_name FROM roles WHERE role_id = OLD.role_id),
                    (SELECT role_name FROM roles WHERE role_id = NEW.role_id));
        END IF;
        IF NEW.email IS DISTINCT FROM OLD.email THEN
            INSERT INTO account_audit_log (user_id, action, old_value, new_value)
            VALUES (NEW.user_id, 'EMAIL_CHANGED', OLD.email, NEW.email);
        END IF;
        IF NEW.is_active IS DISTINCT FROM OLD.is_active THEN
            INSERT INTO account_audit_log (user_id, action, old_value, new_value)
            VALUES (NEW.user_id,
                    CASE WHEN NEW.is_active THEN 'ACCOUNT_REACTIVATED'
                         ELSE 'ACCOUNT_DEACTIVATED' END,
                    OLD.is_active::text, NEW.is_active::text);
        END IF;
    END IF;
    RETURN NULL;   -- AFTER trigger: return value is ignored
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_users_audit
AFTER INSERT OR UPDATE ON users
FOR EACH ROW EXECUTE FUNCTION fn_log_account_change();

-- ---------------------------------------------------------------------
-- TRIGGER 2: when a new active subscription is inserted, automatically
--            close the user's previous active one (upgrade / downgrade)
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_close_previous_subscription() RETURNS trigger AS $$
BEGIN
    IF NEW.status = 'active' THEN
        UPDATE subscriptions
           SET status = 'expired',
               end_date = GREATEST(NEW.start_date, start_date + 1)
         WHERE user_id = NEW.user_id
           AND status = 'active';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_close_previous_subscription
BEFORE INSERT ON subscriptions
FOR EACH ROW EXECUTE FUNCTION fn_close_previous_subscription();

