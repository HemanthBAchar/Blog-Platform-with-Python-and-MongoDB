-- One row per user with role, country, current plan and login summary
CREATE VIEW v_user_overview AS
SELECT u.user_id,
       u.username,
       u.full_name,
       r.role_name,
       c.country_name,
       u.signup_date,
       u.is_active,
       COALESCE(p.plan_name, 'None')      AS current_plan,
       COUNT(l.login_id)                  AS login_count,
       MAX(l.login_at)                    AS last_login
FROM users u
JOIN roles      r ON r.role_id      = u.role_id
JOIN countries  c ON c.country_code = u.country_code
LEFT JOIN subscriptions s ON s.user_id = u.user_id AND s.status = 'active'
LEFT JOIN plans         p ON p.plan_id = s.plan_id
LEFT JOIN user_logins   l ON l.user_id = u.user_id
GROUP BY u.user_id, u.username, u.full_name, r.role_name,
         c.country_name, u.signup_date, u.is_active, p.plan_name;

-- Sign-ups per calendar month with running total
CREATE VIEW v_monthly_signups AS
SELECT DATE_TRUNC('month', signup_date)::date                      AS month,
       COUNT(*)                                                    AS signups,
       SUM(COUNT(*)) OVER (ORDER BY DATE_TRUNC('month', signup_date)) AS cumulative_users
FROM users
GROUP BY DATE_TRUNC('month', signup_date);
