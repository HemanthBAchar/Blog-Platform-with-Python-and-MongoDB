-- schema.sql : relational part (users, roles, plans, subscriptions,
--              logins, audit log).  Target: PostgreSQL 13+.
-- Posts, comments and tags live in MongoDB (see mongo/).
-- Usage:  psql -U postgres -d blogpulse -f schema.sql
